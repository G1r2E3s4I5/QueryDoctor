# Helper dummy connection/cursor that records executed statements
class DummyCursor:
    def __init__(self, fetch_one_result=None, fetch_all_result=None):
        self.commands: List[tuple] = []
        self._fetch_one = fetch_one_result
        self._fetch_all = fetch_all_result or []

    def execute(self, sql: str, params=None):
        # Record executed statements for later assertions
        self.commands.append((sql, params))
        # Reset previous fetch results to avoid cross‑call leakage
        self._fetch_one = None
        self._fetch_all = []
        # Simulate SELECT/INSERT behavior based on the actual SQL patterns used by the app
        if "SELECT query_text" in sql:
            # Return a dummy query text (used later for recommendation generation)
            self._fetch_one = ("SELECT * FROM users",)
        elif "SELECT plan_json" in sql:
            # Return a dummy plan JSON; None indicates no plan was previously collected
            self._fetch_one = (None,)
        elif "INSERT INTO analysis_results" in sql:
            # The endpoint expects the INSERT to RETURNING result_id
            self._fetch_one = (42,)
        elif "SELECT rec_id" in sql:
            # Return rows in the order: rec_id, suggestion, rewritten_sql, confidence
            self._fetch_all = [(1, "Idx suggestion", "CREATE INDEX ...", 0.85)]
        # Other statements (e.g., INSERT into analyzed_queries or query_features) are recorded without fetch results

    def fetchone(self):
        return self._fetch_one

    def fetchall(self):
        return self._fetch_all

    def close(self):
        pass

class DummyConnection:
    def __init__(self, cursor: DummyCursor):
        self._cursor = cursor
        self.closed = False

    def cursor(self):
        return self._cursor

    def commit(self):
        pass

    def rollback(self):
        pass

    def close(self):
        self.closed = True

class DummyContext:
    """Simple context manager that yields the provided connection."""
    def __init__(self, conn):
        self.conn = conn

    def __enter__(self):
        return self.conn

    def __exit__(self, exc_type, exc, tb):
        return False

# Fixture that builds a FastAPI app with the router under test
@pytest.fixture
def client(monkeypatch):
    app = FastAPI()
    app.include_router(analyze_router)
    # Prepare dummy DB objects
    dummy_cur = DummyCursor()
    dummy_conn = DummyConnection(dummy_cur)
    dummy_ctx = DummyContext(dummy_conn)
    # Patch the DB connection utilities to return dummy context managers
    from backend.app.db import connection as conn_mod
    monkeypatch.setattr(conn_mod, "get_project_connection", lambda: dummy_ctx)
    monkeypatch.setattr(conn_mod, "get_target_connection", lambda: dummy_ctx)
    # Patch the ML prediction function to return a deterministic result
    from backend.app.ml import predict as predict_mod
    monkeypatch.setattr(predict_mod, "predict", lambda features: {
        "prediction": "needs_index",
        "model_version": "v1.0",
        "probabilities": {"needs_index": 0.92, "healthy": 0.05, "query_rewrite": 0.02, "full_table_scan": 0.01},
    })
    # Patch the feature extractor to return a simple feature set
    from backend.app.services import feature_extractor as fe_mod
    monkeypatch.setattr(fe_mod, "extract_features", lambda plan: {"seq_scan": 1, "filter_present": True})
    return TestClient(app)

def test_generate_recommendations_success(client):
    """POST /recommendations should return a result_id and a list of recommendations.

    The test verifies that:
    * The endpoint calls the mocked DB connections.
    * The persister inserts rows with the expected parameters.
    * The returned payload contains the recommendations generated by the engine.
    """
    response = client.post("/recommendations", params={"query_id": "dummy-id"})
    assert response.status_code == 200
    payload = response.json()
    assert "result_id" in payload
    assert payload["result_id"] == 42
    assert isinstance(payload["recommendations"], list)
    # At least one recommendation should be present for the mocked prediction
    assert any(rec.get("recommendation_type") == "index_suggestion" for rec in payload["recommendations"])

def test_get_suggestions_success(client):
    """GET /suggestions should retrieve persisted recommendations.

    The dummy cursor is pre‑programmed to return a single row.
    """
    response = client.get("/suggestions", params={"result_id": 42})
    assert response.status_code == 200
    data = response.json()
    assert isinstance(data, list)
    assert data[0]["rec_id"] == 1
    assert data[0]["suggestion"] == "Idx suggestion"
    assert data[0]["rewritten_sql"] == "CREATE INDEX ..."
    assert data[0]["confidence"] == 0.85

def test_recommendations_missing_model(monkeypatch, client):
    """When the prediction function raises, the endpoint returns HTTP 500.
    """
    from backend.app.ml import predict as predict_mod
    def raise_error(_):
        raise RuntimeError("model missing")
    monkeypatch.setattr(predict_mod, "predict", raise_error)
    response = client.post("/recommendations", params={"query_id": "dummy-id"})
    assert response.status_code == 500
    assert "model missing" in response.json()["detail"]

def test_recommendations_no_features(monkeypatch, client):
    """If no plan JSON is available, the engine should still produce a recommendation based on the model.
    """
    # Ensure extract_features returns empty when called with None
    from backend.app.services import feature_extractor as fe_mod
    monkeypatch.setattr(fe_mod, "extract_features", lambda plan: {})
    # Use a mock prediction that yields a healthy label
    from backend.app.ml import predict as predict_mod
    monkeypatch.setattr(predict_mod, "predict", lambda _: {
        "prediction": "healthy",
        "model_version": "v1.0",
        "probabilities": {"healthy": 0.99},
    })
    resp = client.post("/recommendations", params={"query_id": "dummy-id"})
    assert resp.status_code == 200
    payload = resp.json()
    # Healthy path should produce a single "no_action" recommendation
    assert len(payload["recommendations"]) == 1
    assert payload["recommendations"][0]["recommendation_type"] == "no_action"
